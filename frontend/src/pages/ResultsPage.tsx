import { Download, RefreshCcw } from 'lucide-react';
import { Link, useLocation } from 'react-router-dom';
import type { ReconstructionResponse } from '../types';

interface LocationState {
  previewUrl?: string;
  fileName?: string;
  category?: string;
  description?: string;
  result?: ReconstructionResponse;
}

function ResultsPage() {
  const location = useLocation();
  const state = (location.state as LocationState) || {};

  const result = state.result;

  if (!result || !state.previewUrl) {
    return (
      <div className="mx-auto max-w-3xl px-5 py-20 text-center">
        <p className="text-xs font-semibold uppercase tracking-[0.2em] text-[#ad583b]">Reconstruction workspace</p>
        <h1 className="mt-3 font-serif text-4xl text-[#3f3029]">No reconstruction to display</h1>
        <p className="mt-3 text-sm text-[#75645a]">Upload a fabric image to run the available repeat-analysis pipeline.</p>
        <Link to="/upload" className="mt-6 inline-flex items-center gap-2 rounded-full bg-[#ad583b] px-5 py-3 text-sm font-medium text-white">Upload Fabric</Link>
      </div>
    );
  }

  const { tile_dimensions: tileDimensions, reliable } = result.pattern;
  const tileSizeLabel = !reliable
    ? 'No reliable repeat found'
    : tileDimensions.width !== null && tileDimensions.height !== null
      ? `${tileDimensions.width} × ${tileDimensions.height} px`
      : tileDimensions.width !== null
        ? `${tileDimensions.width} px wide`
        : tileDimensions.height !== null
          ? `${tileDimensions.height} px high`
          : 'No reliable repeat found';

  return (
    <div className="mx-auto max-w-7xl px-5 py-12 lg:px-8">
      <div className="mb-6 flex flex-col gap-3 md:flex-row md:items-center md:justify-between">
        <div>
          <p className="text-xs font-semibold uppercase tracking-[0.25em] text-[#7a564d]">Reconstruction workspace</p>
          <h1 className="mt-2 font-serif text-5xl text-[#382B27]">Pattern Reconstruction</h1>
        </div>
        <div className="flex gap-3">
          <a href={result.image_url} download className="inline-flex items-center gap-2 rounded-full bg-[#ad583b] px-4 py-2.5 text-sm font-medium text-white">
            <Download className="h-4 w-4" />
            Download
          </a>
        </div>
      </div>

      <div className="mb-6 border border-[#e7dcc8] bg-[#f9efe6] p-4 text-sm leading-6 text-[#5d4b49]">
        {reliable
          ? 'This classical image-processing preview uses a repeat candidate; it is not AI-generated. The periodicity score is heuristic, not a calibrated probability. Repeated watermarks or partial motifs can be mistaken for a full fabric repeat, so compare the candidate tile and preview with the original before using them.'
          : 'No reliable repeat was detected, so the preview remains unchanged from the uploaded image. Try a sharper, clearly patterned fabric image.'}
      </div>

      <div className="grid gap-6 lg:grid-cols-[1.4fr_0.6fr]">
        <div className={`grid gap-5 ${result.tile_preview_url ? 'md:grid-cols-2 xl:grid-cols-3' : 'md:grid-cols-2'}`}>
          <div className="rounded-lg border border-[#e7dcc8] bg-white p-4">
            <p className="mb-3 text-sm font-medium text-[#382B27]">Original</p>
            <img src={state.previewUrl} alt="Original uploaded fabric" className="h-[320px] w-full rounded-md object-contain" />
          </div>

          {result.tile_preview_url && (
            <div className="rounded-lg border border-[#e7dcc8] bg-white p-4">
              <p className="mb-3 text-sm font-medium text-[#382B27]">Candidate tile — inspect manually</p>
              <img src={result.tile_preview_url} alt="Unmodified crop of the candidate repeating tile; verify it against the original" className="h-[320px] w-full rounded-md object-contain" />
            </div>
          )}

          <div className="rounded-lg border border-[#e7dcc8] bg-white p-4">
            <p className="mb-3 text-sm font-medium text-[#382B27]">{reliable ? 'Candidate repeat preview' : 'Preview'}</p>
            <img src={result.image_url} alt={reliable ? 'Tile-repeat preview generated by the image-processing baseline' : 'Original image; no repeat met the confidence threshold'} className="h-[320px] w-full rounded-md object-contain" />
          </div>
        </div>

        <aside className="rounded-lg border border-[#e7dcc8] bg-white p-5">
          <h2 className="font-serif text-3xl text-[#382B27]">Analysis</h2>
          <div className="mt-5 space-y-4 text-sm text-[#573f3a]">
            <div className="flex items-center justify-between border-b border-[#f0e5d9] pb-2">
              <span>Detected tile size</span>
              <strong>{tileSizeLabel}</strong>
            </div>
            <div className="flex items-center justify-between border-b border-[#f0e5d9] pb-2">
              <span>Dominant direction</span>
              <strong className="capitalize">{result.pattern.direction}</strong>
            </div>
            <div className="flex items-center justify-between border-b border-[#f0e5d9] pb-2">
              <span>Periodicity heuristic</span>
              <strong>{Math.round(result.pattern.confidence)}%</strong>
            </div>
          </div>

          <div className="mt-6">
            <p className="mb-3 text-sm font-medium text-[#382B27]">Dominant colors</p>
            <div className="flex flex-wrap gap-3">
              {result.palette.map((swatch) => (
                <div key={swatch} className="flex flex-col items-center gap-2">
                  <span className="h-10 w-10 rounded-full border border-[#e7dcc8]" style={{ background: swatch }} />
                  <span className="text-[10px] uppercase tracking-[0.08em] text-[#5a4b48]">{swatch}</span>
                </div>
              ))}
            </div>
          </div>

          <div className="mt-7 flex flex-col gap-3">
            <Link to="/upload" className="inline-flex items-center justify-center gap-2 rounded-full border border-[#d7c4a8] bg-[#f9f3eb] px-4 py-3 text-sm font-medium text-[#382B27]">
              <RefreshCcw className="h-4 w-4" />
              Try Another Image
            </Link>
            <Link to="/quality-inspector" className="inline-flex items-center justify-center gap-2 rounded-full bg-[#ad583b] px-4 py-3 text-sm font-medium text-white">Inspect Image Quality</Link>
          </div>
        </aside>
      </div>
    </div>
  );
}

export default ResultsPage;
